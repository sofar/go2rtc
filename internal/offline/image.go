package offline

import (
	"bytes"
	"image"
	"image/color"
	"image/jpeg"
)

const (
	placeholderWidth  = 640
	placeholderHeight = 360
)

// RenderPlaceholder generates a JPEG "Camera Offline" placeholder image.
// The image has a dark background with centered status text rendered as
// simple block-pixel characters (no external font dependency).
func RenderPlaceholder(cameraName, reason string) []byte {
	img := image.NewRGBA(image.Rect(0, 0, placeholderWidth, placeholderHeight))

	// Dark background
	bg := color.RGBA{R: 30, G: 30, B: 30, A: 255}
	for y := range placeholderHeight {
		for x := range placeholderWidth {
			img.Set(x, y, bg)
		}
	}

	// Draw centered text lines
	white := color.RGBA{R: 220, G: 220, B: 220, A: 255}
	red := color.RGBA{R: 220, G: 60, B: 60, A: 255}

	lines := []struct {
		text string
		col  color.RGBA
	}{
		{cameraName, white},
		{"OFFLINE", red},
	}
	if reason != "" {
		lines = append(lines, struct {
			text string
			col  color.RGBA
		}{reason, white})
	}

	// Each character is 6x10 pixels at scale=2 (12x20 actual).
	// Vertical center of the image.
	scale := 2
	charW := 6 * scale
	charH := 10 * scale
	lineSpacing := 6 * scale
	totalH := len(lines)*charH + (len(lines)-1)*lineSpacing
	startY := (placeholderHeight - totalH) / 2

	for i, line := range lines {
		textW := len(line.text) * charW
		startX := (placeholderWidth - textW) / 2
		if startX < 0 {
			startX = 0
		}
		y := startY + i*(charH+lineSpacing)
		drawText(img, startX, y, line.text, line.col, scale)
	}

	var buf bytes.Buffer
	_ = jpeg.Encode(&buf, img, &jpeg.Options{Quality: 80})
	return buf.Bytes()
}

// drawText renders a string using a built-in 5x7 bitmap font, scaled up.
func drawText(img *image.RGBA, x, y int, text string, col color.RGBA, scale int) {
	for _, ch := range text {
		glyph := getGlyph(ch)
		for row := range 7 {
			for col_idx := range 5 {
				if glyph[row]&(1<<(4-col_idx)) != 0 {
					for sy := range scale {
						for sx := range scale {
							px := x + col_idx*scale + sx
							py := y + row*scale + sy
							if px >= 0 && px < placeholderWidth && py >= 0 && py < placeholderHeight {
								img.Set(px, py, col)
							}
						}
					}
				}
			}
		}
		x += 6 * scale
	}
}

// getGlyph returns a 7-row bitmap for a character (5 bits wide per row).
func getGlyph(ch rune) [7]byte {
	if ch >= 'A' && ch <= 'Z' {
		return glyphsUpper[ch-'A']
	}
	if ch >= 'a' && ch <= 'z' {
		return glyphsLower[ch-'a']
	}
	if ch >= '0' && ch <= '9' {
		return glyphsDigit[ch-'0']
	}
	switch ch {
	case ' ':
		return [7]byte{}
	case '-':
		return [7]byte{0, 0, 0, 0x0E, 0, 0, 0}
	case '_':
		return [7]byte{0, 0, 0, 0, 0, 0, 0x1F}
	case '.':
		return [7]byte{0, 0, 0, 0, 0, 0x04, 0}
	case ':':
		return [7]byte{0, 0x04, 0, 0, 0, 0x04, 0}
	case '/':
		return [7]byte{0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10}
	case '(':
		return [7]byte{0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02}
	case ')':
		return [7]byte{0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08}
	}
	// Unknown character: small square
	return [7]byte{0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F}
}

